<?php
/**
 * Fund balance report: for every fund the user can see, posted collections,
 * spending, cash held, advances outstanding and total resources. Each row links to
 * the fund's statement (period movements) on the fund page.
 */
declare(strict_types=1);

require_once dirname(__DIR__) . '/includes/auth_check.php';
require_once APP_ROOT . '/includes/reports.php';
require_once APP_ROOT . '/includes/services/funds.php';
require_institution_context();
require_permission('reports.view');

$status = in_array(get_str('status', 20), ['active', 'suspended', 'closed', 'all'], true) ? get_str('status', 20) : 'active';
[$visibility, $params] = fund_visibility('f');
$funds = db_all(
    "SELECT f.id, f.fund_code, f.fund_name, f.fund_category, f.status FROM fund_accounts f
     WHERE f.institution_id = ? AND {$visibility}" . ($status === 'all' ? '' : ' AND f.status = ?') . ' ORDER BY f.fund_name',
    array_merge([current_institution_id()], $params, $status === 'all' ? [] : [$status])
);
$rows = [];
$totals = ['opening' => 0, 'collected' => 0, 'spent' => 0, 'cash' => 0, 'advances' => 0, 'total' => 0];
foreach ($funds as $fund) {
    $summary = fund_summary((int) $fund['id']);
    $rows[] = $fund + $summary;
    foreach ($totals as $key => $value) {
        $totals[$key] += $summary[$key];
    }
}
$currency = current_currency();
$columns = ['opening' => 'Opening', 'collected' => 'Collected', 'spent' => 'Spent', 'cash' => 'Cash held', 'advances' => 'Advances outstanding', 'total' => 'Total resources'];

if (get_str('export', 10) === 'csv') {
    audit_log('report.exported', 'report', null, current_institution_id(), (int) auth_user()['id'], ['report' => 'fund_balances', 'status' => $status, 'rows' => count($rows)]);
    send_csv('fund_balances_' . date('Ymd') . '.csv', array_merge(['Code', 'Fund', 'Category', 'Status'], array_values($columns)),
        array_map(static fn($r) => array_merge([$r['fund_code'], $r['fund_name'], $r['fund_category'], $r['status']], array_map(static fn($k) => cents_to_decimal($r[$k]), array_keys($columns))), $rows),
        [['Fund balance report', auth_context()['label']], ['Fund status', $status], ['Basis', 'Posted journal entries'], ['Generated', date('Y-m-d H:i') . ' by ' . auth_user()['username']]]);
}

$pageTitle = 'Fund Balance Report';
$activeNav = 'reports';
$breadcrumb = [auth_context()['label'], 'Reports'];
$pageScripts = ['vendor/chartjs/chart.umd.js', 'js/charts.js'];
require APP_ROOT . '/includes/header.php';
?>
<div class="report-header"><h2>Fund Balance Report</h2><p><?= e(auth_context()['label']) ?> · Funds: <?= e(humanize($status)) ?> · As of <?= e(format_datetime(date('Y-m-d H:i:s'))) ?> · Posted entries only · Generated by <?= e(auth_user()['username']) ?></p></div>
<?= page_actions('What each fund has collected and spent, and where its money is now: cash in accounts plus advances not yet liquidated. Figures come from posted entries only.',
    button_link('reports/index.php', 'All Reports', 'bi-arrow-left', 'btn-outline-secondary')
    . '<a class="btn btn-outline-primary" href="' . e(query_url(['export' => 'csv'])) . '"><i class="bi bi-filetype-csv me-1" aria-hidden="true"></i>CSV</a>'
    . '<button class="btn btn-outline-primary" type="button" data-print><i class="bi bi-printer me-1" aria-hidden="true"></i>Print</button>') ?>
<div class="stat-grid">
    <?= stat_card('bi-wallet', 'Total resources', money($totals['total'], $currency), count($rows) . ' fund' . (count($rows) === 1 ? '' : 's')) ?>
    <?= stat_card('bi-cash-stack', 'Cash held', money($totals['cash'], $currency), 'In custody, bank and e-wallets') ?>
    <?= stat_card('bi-wallet2', 'Advances outstanding', money($totals['advances'], $currency), 'Released, not yet liquidated', $totals['advances'] ? 'warning' : 'success') ?>
    <?= stat_card('bi-receipt', 'Spent', money($totals['spent'], $currency), 'Posted expenses', 'info') ?>
</div>
<?php if ($rows): ?>
    <div class="card panel mb-3"><div class="card-header"><h3>Cash and advances by fund</h3></div><div class="card-body">
        <?= chart_canvas(['type' => 'bar', 'labels' => array_column($rows, 'fund_name'), 'datasets' => [
            ['label' => 'Cash held', 'data' => array_map(static fn($r) => chart_amount($r['cash']), $rows)],
            ['label' => 'Advances outstanding', 'data' => array_map(static fn($r) => chart_amount($r['advances']), $rows)],
        ]], 'Cash held and advances outstanding per fund') ?>
    </div></div>
<?php endif; ?>
<div class="card panel">
    <form class="filter-bar" method="get">
        <div class="filter-field"><label for="status">Funds</label><select class="form-select" id="status" name="status" data-autosubmit><?= options_html(['active' => 'Active', 'suspended' => 'Suspended', 'closed' => 'Closed', 'all' => 'All'], $status) ?></select></div>
    </form>
    <?php if (!$rows): ?>
        <div class="card-body"><?= empty_state('bi-wallet', 'No funds match') ?></div>
    <?php else: ?>
        <div class="table-responsive">
            <table class="table table-clean table-report align-middle mb-0">
                <thead><tr><th>Fund</th><?php foreach ($columns as $label): ?><th class="text-end"><?= e($label) ?></th><?php endforeach; ?><th class="d-print-none"></th></tr></thead>
                <tbody>
                <?php foreach ($rows as $row): ?>
                    <tr>
                        <td><div class="fw-semibold"><?= e($row['fund_name']) ?></div><div class="text-muted-sm"><?= e($row['fund_code'] . ' · ' . humanize($row['fund_category'] ?? '')) ?><?= $row['status'] !== 'active' ? ' · ' . e(humanize($row['status'])) : '' ?></div></td>
                        <?php foreach (array_keys($columns) as $key): ?><td class="text-end<?= $key === 'total' ? ' fw-semibold' : '' ?>"><?= e(money($row[$key], $currency)) ?></td><?php endforeach; ?>
                        <td class="actions d-print-none"><a class="btn btn-outline-primary btn-xs" href="<?= e(url('funds/view.php?id=' . $row['id'])) ?>">Statement</a></td>
                    </tr>
                <?php endforeach; ?>
                </tbody>
                <tfoot><tr class="fw-semibold"><td>Total</td><?php foreach (array_keys($columns) as $key): ?><td class="text-end"><?= e(money($totals[$key], $currency)) ?></td><?php endforeach; ?><td class="d-print-none"></td></tr></tfoot>
            </table>
        </div>
    <?php endif; ?>
</div>
<?php require APP_ROOT . '/includes/footer.php'; ?>
